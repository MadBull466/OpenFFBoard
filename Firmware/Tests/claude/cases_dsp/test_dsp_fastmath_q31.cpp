namespace {

const double kPi = 3.14159265358979323846;
const double kTwo31 = 2147483648.0;
const double kTwo29 = 536870912.0;
const double kTwo26 = 67108864.0;
const char *const kDir = "FastMath/FastMathQ31/";

dsp::Pattern pat(const char *name) { return dsp::loadPattern(std::string(kDir) + name); }

int64_t clipQ31(double v) {
	if (v >= 2147483647.0) return 2147483647;
	if (v <= -2147483648.0) return -2147483648LL;
	return (int64_t)std::llround(v);
}

// DEF of arm_sin_q31 / arm_cos_q31 (see the header comment)
double defSin(int32_t x) { return std::sin(2.0 * kPi * (double)x / kTwo31) * kTwo31; }
double defCos(int32_t x) { return std::cos(2.0 * kPi * (double)x / kTwo31) * kTwo31; }

// largest interpolation error of the 512 interval table, in LSB (derivation in the header)
double interpBound() {
	const double h = 2.0 * kPi / 512.0;
	return h * h / 8.0 * kTwo31 + 8.0;
}

// DEF of arm_vlog_q31, q5.26
double defLog(int32_t x) { return std::log((double)x / kTwo31) * kTwo26; }

// deterministic pseudo random values (no <random>: identical on every platform)
uint32_t lcg(uint32_t &s) {
	s = s * 1664525u + 1013904223u;
	return s;
}

}  // namespace

