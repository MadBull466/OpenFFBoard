/*
 * CMSIS-DSP FastMath, q31 (phase P11 group G1, work order FQ31): arm_sin_q31, arm_cos_q31, arm_sqrt_q31,
 * arm_divide_q31, arm_atan2_q31, arm_vlog_q31. Requirement ids: Tests/claude/charters/dsp/CMSIS_DSP_REQUIREMENTS.md.
 *
 * Units and ARM test ids (Libraries/CMSIS-DSP/Testing/Source/Tests/FastMathQ31.cpp, suite "Fast Maths Q31" in
 * Testing/desc.txt:1862-1904; cited as FastMathQ31.cpp:<line>, the function bodies are at the lines given):
 *   test_cos_q31                      :: C1 [cos]     input Angles1_q31, ref Cos1_q31, 23 values
 *   test_sin_q31                      :: C1 [sin]     input Angles1_q31, ref Sin1_q31
 *   test_sqrt_q31                     :: C1 [sqrt]    input SqrtInput1_q31, ref Sqrt1_q31, 1024 values
 *   test_division_q31                 :: C1 [divide]  Numerator1 / Denominator1, ref DivisionValue1_q31 and
 *                                                     DivisionShift1_s16, 2704 values
 *   test_vlog_q31, nb=3, nb=4n, nb=4n+1 :: C1 [vlog] LogInput1_q31, ref Log1_q31: block sizes 125 (all), 3, 8, 11
 *                                         (desc.txt:1897-1900; the 4th argument of PatternMgr reload is the count)
 *   test_atan2_scalar_q31             :: C1 [atan2]   Atan2Input1_q31 (pairs y, x), ref Atan2Ref1_q31, 1001 pairs
 *   test_recip_q31 (desc.txt:1902)    :: NOT covered, see the report: it tests arm_recip_q31, an inline function of
 *                                        dsp/utils.h that none of the six in-scope q31 FastMath functions calls.
 *   FastMathQ63 (test_norm_64_to_32u, test_div_int64_to_int32): NOT covered, see the report: the functions
 *                                        arm_norm_64_to_32u / arm_div_int64_to_int32 are inline functions of
 *                                        dsp/utils.h, called by arm_mean_q31 / arm_var_q15 (Statistics, group G3) and
 *                                        not by any function of this file.
 * Pattern files: Patterns/DSP/FastMath/FastMathQ31/{Angles1,Cos1,Sin1,SqrtInput1,Sqrt1,Numerator1,Denominator1,
 *   DivisionValue1,LogInput1,Log1,Atan2Input1,Atan2Ref1}_q31.txt and DivisionShift1_s16.txt (generated by ARM's
 *   PatternGeneration/FastMath.py with numpy in double precision).
 *
 * ARM tolerances (FastMathQ31.cpp:9-23, units are LSB of the q31 output; SNR threshold 100 dB for all):
 *   SNR_THRESHOLD 100 (:9); ABS_SQRT_ERROR 7 (:16); ABS_ERROR 2200 (sin and cos, :18); ABS_DIV_ERROR 2 (:19);
 *   LOG_ABS_ERROR 2 (:20); ABS_ATAN_ERROR 3 (:22). ARM's checks: sin :FastMathQ31.cpp:118-129, cos :102-115, sqrt
 *   :131-147 (its SNR line is commented out at :143; this file runs it anyway), division :80-100, vlog :46-57,
 *   atan2 :24-43. Division also compares the shift exactly (:98).
 * NEEDS REVIEW (L4): the sin/cos bound of 2200 LSB. ARM's 23 angles are multiples of 1/8, i.e. exactly on the
 *   table nodes (the table has 512 intervals over the full circle, index = x >> 22, 64 nodes per eighth), where the
 *   linear interpolation error is zero. Between the nodes the documented method (linear interpolation of a 512
 *   interval table) has the error derived below, which is 40430 LSB, so 2200 LSB is neither the accuracy of the
 *   method (too tight off the nodes) nor a tight check on the nodes (too loose there). This file adds two DEF checks
 *   instead of changing ARM's bound: on the nodes 3 LSB (derived below) and off the nodes the interpolation bound.
 *
 * Derivations used by the DEF checks (angle mapping from the doc of arm_sin_q31: "input value is in the range
 * [0 +0.9999] and is mapped to a radian value in the range [0 2*PI)", so theta = 2*pi*x / 2^31 for x >= 0; a negative
 * x is mapped to the same angle by adding 0x80000000 as unsigned, which equals theta = 2*pi*x / 2^31 mod 2*pi):
 *   - Node check: table node k holds sin(2*pi*k/512) in q31 (rounded to nearest: 0.5 LSB). At a node the fraction
 *     is 0 and the code computes ((a * 2^31) >> 32) << 1, which clears the lowest bit of a (at most 1 LSB), and a
 *     value of +1.0 saturates to 0x7FFFFFFF (1 LSB). Total at most 2.5 LSB, so the bound used is 3 LSB.
 *   - Interpolation check: for a linear interpolant over an interval of width h of a function f the error is at most
 *     h^2/8 * max|f''|. Here h = 2*pi/512 and |sin''| <= 1, so 1.8835e-5, times 2^31 = 40448 LSB (computed in the test
 *     from h). Add 8 LSB for table rounding and the two truncations of the interpolation arithmetic.
 *   - Log (DEF): the q5.26 output is ln(x / 2^31) * 2^26. The algorithm (arm_scalar_log_q31, "Clay Turner algorithm")
 *     is the same one ARM tests with the 2 LSB bound (:20), used unchanged for the other inputs of this file.
 *   - Sqrt: DEF is sqrt(x / 2^31) * 2^31, bound 7 LSB like ARM (:16).
 *   - Atan2 result is Q2.29 (doc of arm_atan2_q31): ref = atan2(y, x) * 2^29, bound 3 LSB like ARM (:22).
 *   - Divide: the doc says the quotient is "normalized between -1.0 and 1.0" and "shift: shift left value to get the
 *     unnormalized quotient", so n/d = quotient / 2^31 * 2^shift. The code computes temp = floor(|n| * 2^31 / |d|)
 *     (error < 1 LSB of the Q31 ratio) and then drops `shift` bits (error < 2^shift), so the error of the ratio is
 *     below (2^shift + 1) / 2^31.
 *   - C5 against f32: see each test; every bound is the sum of the error bound of the f32 function (its own
 *     documented/ARM tolerance) and of the q31 function.
 *
 * Host vs target (C6): the host runs the portable C path (no ARM_MATH_DSP), the target the intrinsic path (e.g.
 *   __QSUB instead of the INT32_MIN check in arm_atan_q31, __CLZ builtin on both). Results of these q31 functions
 *   are integer arithmetic and are expected to be identical, but the host cannot prove the target path. The f32
 *   reference functions of the C5 tests (arm_sin_f32, arm_cos_f32, arm_sqrt_f32, arm_atan2_f32, arm_vlog_f32 = logf)
 *   may differ in the last float bits on the target (FMA contraction). The library is C code: UBSan reports left
 *   shifts of negative values (`sinVal << 1`) in the sanitizer build if they occur.
 */
